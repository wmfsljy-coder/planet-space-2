/* 행성우주과학 Ⅱ-2 — 소단원 잇기 카드
   한 소단원이 뒤 소단원에 넘겨주는 것을 여기 한 곳에 적는다.
   · 넘겨주는 이야기의 결말 아래 '넘겨주기 카드'(sthHandoff)
   · 그것을 쓰는 이야기 맨 앞 '이어받기 카드'(sthBridge) — 앞 소단원을 건너뛰었거나 아직 안 끝냈을 때만 펼쳐진다.
   엔진: ../assets/scope.js. episodes.js(worked.js) 다음에 불러온다.
   잇는 줄: 01 → 02(밝기로 잰 거리·색지수), 01 → 03(우리은하의 생김새·헤일로). 04는 앞 이야기 없이 시작할 수 있다. */
(function () {
"use strict";

var D01 = [
  "성단의 별은 모두 같은 거리에 있다. 관측한 주계열을 <b>표준 주계열</b>과 겹치면, 내려간 만큼이 <b>거리 지수 m − M = 5 log(d / 10 pc)</b>이고 여기서 거리가 나온다.",
  "C-M도의 가로축 <b>색지수 B−V</b>는 별의 색이다. 값이 작을수록 파랗고(뜨겁고), 클수록 붉다(차갑다).",
  "우리은하는 얇은 <b>원반</b>(나선팔·산개 성단·성간 물질), 중심의 <b>팽대부</b>, 그 둘레를 공처럼 감싼 <b>헤일로</b>(구상 성단)로 이루어져 있고, 태양은 중심에서 약 <b>8 kpc</b> 떨어진 원반 속에 있다."
];

/* 01 → 넘겨주기 */
window.sthHandoff({
  ep: "epA", title: "이 이야기에서 챙겨 갈 세 줄", lines: D01,
  note: "02 「성간 티끌」에서는 <b>밝기로 잰 거리</b>와 <b>색지수</b>가, 03 「은하의 질량과 암흑 물질」에서는 <b>우리은하의 생김새와 헤일로</b>가 다시 쓰입니다."
});

/* 02 ← 01 */
window.sthBridge({
  ep: "epB", need: "01", doneKey: "epA",
  lines: [D01[0], D01[1], "이 이야기에서는 성단의 <b>밝기로 구한 거리</b>와 <b>각지름</b>으로 구한 크기를 견주고, 별의 <b>색지수</b>가 원래 색과 얼마나 다른지 봅니다."],
  check: { q: "어떤 성단의 거리 지수 m − M가 10이다. 이 성단까지의 거리는?", options: ["10 pc", "100 pc", "1,000 pc", "10,000 pc"], a: 2, why: "10 = 5 log(d / 10) → d / 10 = 100 → d = 1,000 pc." }
});

/* 03 ← 01 */
window.sthBridge({
  ep: "epC", need: "01", doneKey: "epA",
  lines: [D01[2], "이 이야기에서는 은하 중심에서 바깥으로 가며 별들이 <b>얼마나 빠르게 도는지</b>를 잽니다. 거리는 은하 중심에서 잰 kpc이고, 빠르기는 별빛의 도플러 이동으로 잽니다."],
  check: { q: "구상 성단이 흩어져 있는, 원반을 공처럼 감싼 부분은?", options: ["원반", "팽대부", "헤일로", "나선팔"], a: 2, why: "구상 성단은 늙은 별의 무리로 공 모양 헤일로에 퍼져 있습니다. 이 이야기의 ‘암흑 물질 헤일로’도 은하를 공처럼 감싼 영역입니다." }
});

/* 04 — 시작 전 */
window.sthBridge({
  ep: "epD", always: true, title: "시작 전 1분 · 이 이야기에 필요한 것은 두 가지뿐",
  lines: [
    "광원이 멀어지면 그 빛의 스펙트럼선이 <b>파장이 긴 쪽(붉은 쪽)</b>으로 밀린다(도플러 효과).",
    "먼 은하의 거리는 <b>Mpc(메가파섹)</b>으로 잰다. <b>1 Mpc = 100만 pc ≈ 326만 광년</b>"
  ],
  note: "01~03 이야기를 하지 않았어도 바로 시작할 수 있습니다."
});
})();
