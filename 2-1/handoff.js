/* 행성우주과학 Ⅱ-1 — 소단원 잇기 카드
   한 소단원이 뒤 소단원에 넘겨주는 것을 여기 한 곳에 적는다.
   · 넘겨주는 이야기의 결말 아래 '넘겨주기 카드'(sthHandoff)
   · 그것을 쓰는 이야기 맨 앞 '이어받기 카드'(sthBridge) — 앞 소단원을 건너뛰었거나 아직 안 끝냈을 때만 펼쳐진다.
   엔진: ../assets/scope.js. episodes.js 다음에 불러온다. */
(function () {
"use strict";

var D02 = [
  "가까운 별은 <b>연주 시차</b>로 잰다. <b>거리(pc) = 1 ÷ 연주 시차(″)</b>. 연주 시차가 1″이면 1 pc(약 3.26 광년)이다.",
  "먼 별은 <b>밝기</b>로 잰다. 그 별을 10 pc에 두었을 때의 밝기(절대 등급 M)를 알면, 보이는 밝기(겉보기 등급 m)와 견주어 거리가 나온다. <b>m − M = 5 log d − 5</b>",
  "두 자는 <b>이어 붙여</b> 쓴다. 밝기 자의 눈금(절대 등급)은 시차로 거리를 아는 가까운 별에서 얻는다."
];

/* 02 — 시작 전 */
window.sthBridge({
  ep: "epB", always: true, title: "시작 전 1분 · 이 이야기에 필요한 것은 두 가지뿐",
  lines: [
    "각도를 아주 잘게 쪼갠 단위: <b>1° = 60′(분) = 3600″(초)</b>",
    "지구는 1년에 태양을 한 바퀴 돈다. 그래서 <b>반년 뒤에는 궤도 반대편</b>, 약 3억 km 떨어진 자리에서 하늘을 본다."
  ],
  note: "01 「태양 관측」을 하지 않았어도 바로 시작할 수 있습니다."
});

/* 02 → 넘겨주기 */
window.sthHandoff({
  ep: "epB", title: "이 이야기에서 챙겨 갈 세 줄", lines: D02,
  note: "03 「별의 운동과 질량」에서는 접선속도를 구할 때 <b>거리</b>가, 04 「변광성」에서는 먼 은하를 잴 때 <b>밝기 자</b>가 다시 쓰입니다."
});

/* 03 ← 02 */
window.sthBridge({
  ep: "epC", need: "02", doneKey: "epB",
  lines: [D02[0], "이 이야기에서는 하늘을 가로지르는 빠르기(접선속도)를 구할 때 그 거리가 들어갑니다. <b>vt = 4.74 × 고유 운동(″/년) × 거리(pc)</b>"],
  check: { q: "연주 시차가 0.2″인 별까지의 거리는?", options: ["0.2 pc", "2 pc", "5 pc", "20 pc"], a: 2, why: "거리 = 1 ÷ 0.2 = 5 pc. 시차가 작을수록 멀다." }
});

/* 04 ← 02 */
window.sthBridge({
  ep: "epD", need: "02", doneKey: "epB",
  lines: [D02[1], D02[2], "이 이야기의 세페이드 변광성과 Ia형 초신성은 <b>절대 등급을 아는 별(표준 촛불)</b>이라서 밝기 자로 쓸 수 있습니다."],
  check: { q: "절대 등급이 −19.3인 초신성이 19.5등급으로 보였다. 거리를 구하려면 무엇을 쓸까?", options: ["연주 시차", "m − M = 5 log d − 5", "케플러 제3법칙"], a: 1, why: "너무 멀어 시차는 닿지 않는다. 절대 등급을 아니 밝기 자를 쓴다." }
});
})();
